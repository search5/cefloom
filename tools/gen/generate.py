"""Generate the PHP binding of the CEF API.

    python tools/gen/generate.py                      # write the generated files
    python tools/gen/generate.py --check              # fail if they are out of date
    python tools/gen/generate.py --report             # print the coverage summary

The input is the header set of a CEF distribution (--cef-root, default: the one of the cefweaver checkout
next to this project). The generated files are committed, so building the extension does not need the
generator.

Outputs (ext/generated/): cl_gen.h, forwarders.h, structs.cc, enums.cc, lib_<Class>.cc, client_<Class>.cc,
cef_functions.cc, register_all.cc, sources.m4; php/cefloom.stub.php; the coverage report page of the wiki.
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import emit_stub  # noqa: E402
from emit_client import ClientEmitter  # noqa: E402
from emit_common import Names  # noqa: E402
from emit_data import DataEmitter  # noqa: E402
from emit_lib import LibEmitter  # noqa: E402
from model import Model  # noqa: E402
from scope import HANDWRITTEN_FUNCTIONS, HANDWRITTEN_METHODS, Scope  # noqa: E402
from typesys import plan_class, plan_method  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
DEFAULT_CEF_ROOT = os.path.join(os.path.dirname(ROOT), "cefweaver_clone", "cefweaver", "build", "native", "cef")
OUT_DIR = os.path.join(ROOT, "ext", "generated")
STUB = os.path.join(ROOT, "php", "cefloom.stub.php")
REPORT = os.path.join(ROOT, "llm-wiki", "pages", "reference", "coverage-report.md")
BANNER = "GENERATED by tools/gen/generate.py. DO NOT EDIT."


def cef_version(cef_root):
    with open(os.path.join(cef_root, "include", "cef_version.h"), encoding="utf-8") as f:
        return re.search(r'#define CEF_VERSION "([^"]+)"', f.read()).group(1)


def build_all(cef_root):
    model = Model(cef_root)
    # structs with arrays and plain C structs without a C++ class are not generated (shared textures)
    model.structs = {k: v for k, v in model.structs.items() if not v.raw and not any(f.array for f in v.fields)}
    scope = Scope(model)
    names = Names(model, scope)
    version = cef_version(cef_root)
    header = "// " + BANNER + "\n// CEF " + version + "\n"
    files = {}
    listings = {}

    lib = LibEmitter(model, scope)
    client = ClientEmitter(model, scope)
    data = DataEmitter(model, names)

    # classes
    for cls in scope.library_classes:
        plans = plan_class(model, scope, cls)
        text, listing = lib.emit_class(cls, plans)
        files["lib_%s.cc" % cls.get_name()] = header + text
        listings[cls.get_name()] = ("library", listing)
    forwarders = [header, "#ifndef CEFLOOM_FORWARDERS_H_", "#define CEFLOOM_FORWARDERS_H_", '#include "cl_gen.h"', ""]
    for cls in scope.client_classes:
        plans = plan_class(model, scope, cls)
        text, listing = client.emit_class(cls, plans)
        files["client_%s.cc" % cls.get_name()] = header + text
        listings[cls.get_name()] = ("client", listing)
        forwarders += client.forwarder(cls, [p for p in plans if p.supported and not p.static])
    forwarders.append("#endif  // CEFLOOM_FORWARDERS_H_")
    files["forwarders.h"] = "\n".join(forwarders) + "\n"

    # global functions
    fplans = [plan_method(model, scope, "", model.functions[n], client_side=False, static=True)
              for n in scope.functions]
    text, listing = lib.emit_cef(fplans)
    files["cef_functions.cc"] = header + text
    listings["Cef (global functions)"] = ("functions", listing)

    files["structs.cc"] = header + data.emit_structs()
    files["enums.cc"] = header + data.emit_enums()
    files["cl_gen.h"] = header + emit_header(model, scope, names)
    files["register_all.cc"] = header + emit_register_all(scope)
    sources = sorted(f for f in files if f.endswith(".cc"))
    files["sources.m4"] = "dnl " + BANNER + "\nCL_GENERATED_SOURCES=\"" + " ".join(
        "generated/" + s for s in sources) + "\"\n"
    return model, scope, files, listings, version


def emit_header(model, scope, names):
    headers = sorted({model.header_path(c) for c in list(scope.library_classes) + list(scope.client_classes)} |
                     {"include/" + model.functions[n].get_file_name().replace("\\", "/").split("include/")[-1]
                      for n in scope.functions})
    L = ["#ifndef CEFLOOM_CL_GEN_H_", "#define CEFLOOM_CL_GEN_H_", "", '#include "cl_runtime.h"', ""]
    L += ['#include "%s"' % h for h in headers]
    L += ['#include "include/internal/cef_types_wrappers.h"', ""]
    L += ["ZEND_BEGIN_ARG_INFO_EX(arginfo_cl_private_ctor, 0, 0, 0)", "ZEND_END_ARG_INFO()",
          "[[maybe_unused]] static ZEND_NAMED_FUNCTION(cl_private_ctor) {}", ""]
    L.append("// library classes (implemented by CEF)")
    for cls in scope.library_classes:
        n = cls.get_name()
        L.append("extern zend_class_entry* ce_%s;" % n)
        L.append("void cl_register_%s();" % n)
        L.append("void cl_wrap_%s(zval* rv, %s* p);" % (n, n))
    L.append("")
    L.append("// client classes (implemented by the application)")
    for cls in scope.client_classes:
        n = cls.get_name()
        L.append("extern zend_class_entry* ce_%s;" % n)
        L.append("void cl_register_%s();" % n)
        L.append("CefRefPtr<%s> cl_make_%s(zend_object* o);" % (n, n))
    L.append("")
    L.append("// value structs")
    for k in sorted(model.structs):
        si = model.structs[k]
        L.append("extern zend_class_entry* ce_%s;" % si.cls)
        L.append("void cl_to_zval_%s(zval* zv, const %s& s);" % (si.cname, si.cname))
        L.append("void cl_from_zval_%s(zend_object* o, %s* s);" % (si.cname, si.cname))
        L.append("void cl_default_%s(zval* zv);" % si.cname)
    L += ["", "void cl_register_structs();", "void cl_register_enums();", "void cl_register_Cef();",
          "void cl_register_all();", "extern zend_class_entry* ce_Cef;",
          "extern const zend_function_entry cl_generated_cef_methods[];", "",
          "// implemented by hand (ext/src)", "void cl_core_schedule_pump_work(int64_t delay_ms);", "",
          "#endif  // CEFLOOM_CL_GEN_H_", ""]
    return "\n".join(L)


def emit_register_all(scope):
    L = ['#include "cl_gen.h"', "", "void cl_register_all() {", "  cl_register_enums();", "  cl_register_structs();"]
    for cls in scope.library_classes:
        L.append("  cl_register_%s();" % cls.get_name())
    for cls in scope.client_classes:
        L.append("  cl_register_%s();" % cls.get_name())
    L += ["  cl_register_Cef();", "}", ""]
    return "\n".join(L)


