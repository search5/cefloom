def report_text(model, scope, listings, version):
    total = generated = hand = 0
    reasons = {}
    rows = []
    for name, (side, listing) in sorted(listings.items()):
        g = sum(1 for _, s in listing if s == "generated")
        h = sum(1 for _, s in listing if s == "handwritten")
        n = len(listing)
        total += n
        generated += g
        hand += h
        rows.append("| %s | %s | %d | %d | %d |" % (name, side, n, g, n - g - h) if False else
                    "| %s | %s | %d | %d | %d | %d |" % (name, side, n, g, h, n - g - h))
        for plan, status in listing:
            if status.startswith("not generated"):
                reasons.setdefault(status[len("not generated: "):], []).append("%s.%s" % (name, plan.cef_name))
    L = ["---", "title: 생성기 커버리지 보고서", "type: reference", "sources:",
         "  - cefloom/tools/gen/generate.py", "  - cefloom/tools/gen/scope.py", "  - cefloom/tools/gen/typesys.py",
         "updated: 2026-10-12", "generated: true", "---", "",
         "# 생성기 커버리지 보고서", "",
         "`python tools/gen/generate.py`가 만드는 페이지입니다. 직접 고치지 않습니다. 입력은 CEF %s의 헤더입니다." % version, "",
         "## 요약", "",
         "- 클래스: 라이브러리 %d개, 클라이언트 %d개. 구조체 %d개, 열거형 %d개(읽지 못한 열거형 %d개), 전역 함수 %d개." % (
             len(scope._library), len(scope._client), len(model.structs), len(model.enum_defs),
             len(model.enum_skipped), len(scope.functions)),
         "- 메서드와 함수 %d개 중 생성 %d개, 손으로 작성 %d개, 생성하지 못함 %d개." % (
             total, generated, hand, total - generated - hand),
         "- 범위에서 뺀 것: 렌더러 프로세스 클래스, 소유 포인터 클래스, 테스트 헤더. 이유는 `tools/gen/scope.py`에 있습니다.", "",
         "## 생성하지 못한 이유", ""]
    for reason, items in sorted(reasons.items(), key=lambda kv: -len(kv[1])):
        L.append("- %s (%d): %s" % (reason, len(items), ", ".join(sorted(items)[:12]) + (" ..." if len(items) > 12 else "")))
    L += ["", "## 클래스별", "", "| 클래스 | 종류 | 메서드 | 생성 | 손으로 작성 | 생성하지 못함 |", "| --- | --- | --- | --- | --- | --- |"]
    L += rows
    if model.enum_skipped:
        L += ["", "## 읽지 못한 열거형", ""]
        L += ["- %s: %s" % (k, v) for k, v in sorted(model.enum_skipped.items())]
    L += ["", "## 관련 페이지", "", "- [바인딩 생성기 계획](../concepts/binding-generator-plan.md)", ""]
    return "\n".join(L)


def write_if_changed(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                return False
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--cef-root", default=os.environ.get("CEF_ROOT", DEFAULT_CEF_ROOT))
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--report", action="store_true")
    args = parser.parse_args()

    model, scope, files, listings, version = build_all(args.cef_root)
    outputs = {os.path.join(OUT_DIR, k): v for k, v in files.items()}
    outputs[STUB] = emit_stub.emit(model, scope, listings, version, BANNER)
    outputs[REPORT] = report_text(model, scope, listings, version)

    if args.report:
        print(outputs[REPORT])
        return 0

    stale = [os.path.join(OUT_DIR, n) for n in os.listdir(OUT_DIR)
             if n.endswith((".cc", ".h", ".m4")) and os.path.join(OUT_DIR, n) not in outputs] \
        if os.path.isdir(OUT_DIR) else []
    if args.check:
        bad = []
        for path, text in outputs.items():
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
                bad.append(path)
        bad += stale
        for path in bad:
            print("out of date:", os.path.relpath(path, ROOT))
        return 1 if bad else 0

    changed = [p for p, t in outputs.items() if write_if_changed(p, t)]
    for path in stale:
        os.remove(path)
    print("%d files, %d written, %d removed" % (len(outputs), len(changed), len(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
